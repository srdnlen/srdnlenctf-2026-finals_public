#!/usr/bin/env python3
"""Render the 5x7 font to a PNG so glyph shapes can be eyeballed.

The font is generated by gen_font.py; this shows the result at a size where
the confusable pairs (g/9, 0/O, 1/l/I, p/o, ...) can be checked, which
matters because flags are copied out of the game by hand.

Usage: font_preview.py [text] [scale] [out.png]
"""
import re
import sys

from PIL import Image, ImageDraw

FONT = "source/font5x7.c"
GLYPH = re.compile(r"/\* '(.|\\.)' \*/\s*\{\s*((?:0x[0-9A-Fa-f]{2},\s*){7})\}",
                   re.S)


def load(path):
    with open(path) as fh:
        src = fh.read()
    glyphs = {}
    for ch, body in GLYPH.findall(src):
        glyphs[ch] = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", body)]
    return glyphs


def main():
    text = sys.argv[1] if len(sys.argv) > 1 else "g9qypo0O1lI"
    scale = int(sys.argv[2]) if len(sys.argv) > 2 else 6
    out = sys.argv[3] if len(sys.argv) > 3 else "font-preview.png"

    glyphs = load(FONT)
    width = len(text) * 6 * scale + scale
    image = Image.new("RGB", (width, 9 * scale), (16, 16, 24))
    draw = ImageDraw.Draw(image)

    x = scale
    for ch in text:
        rows = glyphs.get(ch)
        if rows is None:
            raise SystemExit(f"no glyph for {ch!r}")
        for ry, row in enumerate(rows):
            for rx in range(5):
                if row & (0x10 >> rx):
                    draw.rectangle(
                        [x + rx * scale, scale + ry * scale,
                         x + rx * scale + scale - 1, scale + ry * scale + scale - 1],
                        fill=(250, 240, 200))
        x += 6 * scale

    image.save(out)
    print(out)


if __name__ == "__main__":
    main()
