#!/usr/bin/env python3
"""Generate the flag payload (source/flag_data.c + flag_data.h).

The payload is the flag text in plaintext.  Players only ever run the shipped
.dol -- they never receive the binary or the source -- so the payload is not
obfuscated: there is nothing to reverse in a build they cannot obtain.

The payload lives in its own translation unit and its length is a *runtime*
value, so the player build (no flag) and the station build compile to exactly
the same code -- only the payload bytes differ.  Makefile.wii's wipe step
rewrites this file zeroed after the build, so the plaintext does not persist
in the source tree.

  tools/mkflag.py --none                      redacted payload (all zero)
  tools/mkflag.py --flag 'srdnlen{...}'       station payload
  tools/mkflag.py --selftest                  check the payload

Options: --name NAME (default flag_data), --out-dir DIR (default source)
"""
import argparse
import os
import sys

FLAG_MAX = 128


def header_text(name):
    return f"""/* Generated by tools/mkflag.py -- do not edit. */
#ifndef PWNCHUCK_FLAG_DATA_H
#define PWNCHUCK_FLAG_DATA_H

#include "types.h"

#define FLAG_MAX {FLAG_MAX}

/* payload bytes (the flag text) and the number of significant payload bytes
 * (0 when this build carries no flag) */
extern const u8 g_flag_payload[FLAG_MAX];
extern const u8 g_flag_len;

#endif
"""


def source_text(name, flag):
    body = flag if flag else b""
    rows = [", ".join(f"0x{b:02x}" for b in body[i:i + 12]) for i in range(0, len(body), 12)]
    payload = ",\n\t".join(rows) if rows else "0x00"
    return f"""/* Generated by tools/mkflag.py -- do not edit. */
#include "{name}.h"

const u8 g_flag_payload[FLAG_MAX] = {{
	{payload}
}};

const u8 g_flag_len = {len(body)};
"""


def write(name, out_dir, flag):
    os.makedirs(out_dir, exist_ok=True)
    header = os.path.join(out_dir, f"{name}.h")
    source = os.path.join(out_dir, f"{name}.c")
    with open(header, "w") as fh:
        fh.write(header_text(name))
    with open(source, "w") as fh:
        fh.write(source_text(name, flag))
    print(f"wrote {header} and {source}: {len(flag) if flag else 0} payload bytes")


def selftest():
    for flag in (b"srdnlen{selftest}", b"x", b"srdnlen{" + b"a" * 100 + b"}"):
        assert source_text("flag_data", flag) == source_text("flag_data", flag), \
            "payload generation is not deterministic"
        assert len(flag) <= FLAG_MAX - 1, "flag is longer than the payload table"
    assert "0x00" in source_text("flag_data", None), "redacted payload is not zeroed"
    assert "g_flag_len = 0;" in source_text("flag_data", None), \
        "redacted payload has a non-zero length"
    print("mkflag selftest: ok")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--flag", default=None, help="the flag text to embed")
    ap.add_argument("--none", action="store_true", help="write a redacted payload")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--name", default="flag_data")
    ap.add_argument("--out-dir", default="source")
    args = ap.parse_args()

    if args.selftest:
        selftest()
        return 0
    if args.flag and args.none:
        ap.error("--flag and --none are mutually exclusive")
    write(args.name, args.out_dir, args.flag.encode() if args.flag else None)
    return 0


if __name__ == "__main__":
    sys.exit(main())
